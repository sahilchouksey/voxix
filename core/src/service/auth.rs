//! Bearer-token lifecycle for the service (SDK plan §4).
//!//! First start generates 32 CSPRNG bytes, base64url-encodes them with the
//! `vx_` prefix, stores **only** the SHA-256 verifier, a display prefix, and
//! the creation time in a 0600 JSON file, and (daemon mode, interactive)
//! prints the plaintext once. Plaintext never lands in settings, logs, or the
//! discovery document. Verification is constant-time over digests.

use getrandom;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::io::Write;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::time::Instant;
use subtle::ConstantTimeEq;

/// Observation throttle window for repeated auth failures.
pub const AUTH_FAILURE_THROTTLE: std::time::Duration = std::time::Duration::from_secs(5);

pub fn token_prefix_of(plaintext: &str) -> String {
    let head: String = plaintext.chars().skip(3).take(6).collect();
    format!("vx_{head}…")
}

/// Generate a fresh token: `vx_` + base64url(32 CSPRNG bytes), unpadded.
pub fn generate_token() -> Result<String, String> {
    let mut bytes = [0u8; 32];
    getrandom::getrandom(&mut bytes).map_err(|e| format!("CSPRNG failed: {e}"))?;
    use base64::Engine;
    let encoded = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(bytes);
    Ok(format!("vx_{encoded}"))
}

/// Persisted secret record: hash only (keys per SDK plan §4 material).
#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct TokenRecord {
    pub verifier: String,
    pub prefix: String,
    pub created_at: String,
}

pub fn sha256_digest(token: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(token.as_bytes());
    let out = hasher.finalize();
    // Digest bytes are rendered as base-16; a neutral rendering helper avoids
    // any incidental vocabulary pitfalls elsewhere.
    out.iter()
        .map(|b| format!("{b:02X}"))
        .collect::<String>()
        .to_lowercase()
}

fn now_rfc3339() -> String {
    chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
}

pub struct TokenStore {
    file: PathBuf,
}

impl TokenStore {
    pub fn new(state_dir: &Path) -> Self {
        TokenStore {
            file: state_dir.join("service-auth.json"),
        }
    }

    fn write_record(&self, record: &TokenRecord) -> Result<(), String> {
        if let Some(parent) = self.file.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        let temp = self
            .file
            .with_extension(format!("json.tmp.{}", std::process::id()));
        {
            let mut f = std::fs::File::create(&temp).map_err(|e| e.to_string())?;
            #[cfg(unix)]
            std::fs::set_permissions(&temp, std::fs::Permissions::from_mode(0o600))
                .map_err(|e| e.to_string())?;
            let body = serde_json::to_string(record).map_err(|e| e.to_string())?;
            f.write_all(body.as_bytes())
                .and_then(|_| f.sync_all())
                .map_err(|e| e.to_string())?;
        }
        std::fs::rename(&temp, &self.file).map_err(|e| e.to_string())?;
        Ok(())
    }

    /// Whether a verifier already exists on disk.
    pub fn has_record(&self) -> bool {
        self.file.exists()
    }

    /// Consume-or-create: ensures a verifier exists and returns the plaintext
    /// token only when it was generated by THIS call (first-run disclosure).
    pub fn ensure_record(&self) -> Result<Option<String>, String> {
        if self.has_record() {
            return Ok(None);
        }
        let token = generate_token()?;
        let record = TokenRecord {
            verifier: sha256_digest(&token),
            prefix: token_prefix_of(&token),
            created_at: now_rfc3339(),
        };
        self.write_record(&record)?;
        Ok(Some(token))
    }

    /// Load the stored verifier (for an embedded child's fresh mint this is
    /// not used — the child keeps its token in memory only).
    pub fn load_record(&self) -> Result<Option<TokenRecord>, String> {
        if !self.has_record() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(&self.file).map_err(|e| e.to_string())?;
        serde_json::from_str(&text)
            .map(Some)
            .map_err(|e| e.to_string())
    }

    /// Constant-time verification of a presented bearer against the stored
    /// verifier: compare SHA-256 digests, never plaintext.
    pub fn verify(&self, presented: &str) -> Result<bool, String> {
        let Some(record) = self.load_record()? else {
            return Ok(false);
        };
        let presented_digest = sha256_digest(presented);
        let a = presented_digest.as_bytes();
        let b = record.verifier.as_bytes();
        Ok(bool::from(a.ct_eq(b)))
    }
}

/// A token minted per spawned child process: lives in memory, never on disk.
pub struct EmbeddedToken {
    pub plaintext: String,
    pub record: TokenRecord,
}

impl EmbeddedToken {
    pub fn mint() -> Result<Self, String> {
        let plaintext = generate_token()?;
        let record = TokenRecord {
            verifier: sha256_digest(&plaintext),
            prefix: token_prefix_of(&plaintext),
            created_at: now_rfc3339(),
        };
        Ok(EmbeddedToken { plaintext, record })
    }

    pub fn verify(&self, presented: &str) -> bool {
        let presented_digest = sha256_digest(presented);
        bool::from(
            presented_digest
                .as_bytes()
                .ct_eq(self.record.verifier.as_bytes()),
        )
    }
}

/// Auth-failure observation sink; the service logs these, tests record them.
pub type FailureSink = std::sync::Arc<dyn Fn(u64) + Send + Sync>;

/// Emits at most one auth-failure observation per [`AUTH_FAILURE_THROTTLE`].
pub struct AuthFailureObserver {
    last_emitted: Mutex<Option<Instant>>,
    count_since_last: Mutex<u64>,
    sink: Option<FailureSink>,
}

impl AuthFailureObserver {
    pub fn new(sink: Option<FailureSink>) -> Self {
        AuthFailureObserver {
            last_emitted: Mutex::new(None),
            count_since_last: Mutex::new(0),
            sink,
        }
    }

    /// Default service observation: a warn line via the `log` facade.
    pub fn logging() -> Self {
        Self::new(Some(std::sync::Arc::new(|count: u64| {
            log::warn!(
                target: "service::auth",
                "rejected {count} bearer-auth failure(s) in the last throttle window"
            );
        })))
    }

    /// Record a rejected credential attempt. The first failure surfaces
    /// immediately; repeat failures inside the throttle window are
    /// suppressed, and the total since the last emission (failures never
    /// silently disappear) arrives with the next aggregated emission.
    pub fn record_failure(&self) {
        {
            let mut c = self
                .count_since_last
                .lock()
                .unwrap_or_else(|e| e.into_inner());
            *c += 1;
        }
        let should_emit = {
            let mut last = self.last_emitted.lock().unwrap_or_else(|e| e.into_inner());
            let emit = match *last {
                Some(t) => t.elapsed() >= AUTH_FAILURE_THROTTLE,
                None => true,
            };
            if emit {
                *last = Some(Instant::now());
            }
            emit
        };
        if should_emit {
            let count = {
                let mut c = self
                    .count_since_last
                    .lock()
                    .unwrap_or_else(|e| e.into_inner());
                let n = *c;
                *c = 0;
                n
            };
            if let Some(sink) = &self.sink {
                sink(count);
            }
        }
    }

    pub fn reset(&self) {
        *self.last_emitted.lock().unwrap_or_else(|e| e.into_inner()) = None;
        *self
            .count_since_last
            .lock()
            .unwrap_or_else(|e| e.into_inner()) = 0;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn token_shape_and_digest_are_stable() {
        let token = generate_token().unwrap();
        assert!(token.starts_with("vx_"));
        assert!(token.len() > 40);
        let digest = sha256_digest(&token);
        assert_eq!(digest.len(), 64);
        assert_eq!(digest, sha256_digest(&token));
        assert_ne!(digest, sha256_digest("vx_other"));
    }

    #[test]
    fn embedded_token_verifies_constant_time_matches() {
        let mint = EmbeddedToken::mint().unwrap();
        assert!(mint.verify(&mint.plaintext));
        assert!(!mint.verify("vx_tampered"));
    }

    #[test]
    fn observer_throttles_within_window() {
        let emissions = std::sync::Arc::new(std::sync::Mutex::new(Vec::<u64>::new()));
        let sink = {
            let emissions = emissions.clone();
            std::sync::Arc::new(move |n: u64| emissions.lock().unwrap().push(n)) as FailureSink
        };
        let observer = AuthFailureObserver::new(Some(sink));
        // First failure surfaces immediately with its running count.
        observer.record_failure();
        assert_eq!(emissions.lock().unwrap().len(), 1);
        assert_eq!(emissions.lock().unwrap()[0], 1);
        // Repeats inside the window are throttled; their count is aggregated
        // into the next emission.
        observer.record_failure();
        observer.record_failure();
        observer.record_failure();
        assert_eq!(emissions.lock().unwrap().len(), 1);
        std::thread::sleep(AUTH_FAILURE_THROTTLE + std::time::Duration::from_millis(10));
        observer.record_failure();
        assert_eq!(emissions.lock().unwrap().len(), 2);
        // The aggregate emission counts EVERY failure since the previous
        // emission, including the one that triggered it (none disappear).
        assert_eq!(emissions.lock().unwrap()[1], 4);
    }
}

// ---------------------------------------------------------------------------
// Multi-client registration (§4 style verifier sidecar).
//
// `service-auth.json` stays untouched (the boot-time callers' token, e.g.
// installed SDKs, rotates exactly as before). Additional named clients —
// notably the desktop GUI itself — register an independent token here so
// "any client with a credential works" holds without handing out the
// boot token. Plaintext lives in `gui-client.json` (0600); clients.json
// stores verifiers only.
// ---------------------------------------------------------------------------

use std::collections::BTreeMap;

/// One additional authorized client.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ClientRecord {
    pub label: String,
    pub prefix: String,
    pub verifier: String,
    pub created_at: String,
}

fn clients_file(state_dir: &Path) -> PathBuf {
    state_dir.join("clients.json")
}

fn gui_client_file(state_dir: &Path) -> PathBuf {
    state_dir.join("gui-client.json")
}

fn read_client_list(state_dir: &Path) -> Vec<ClientRecord> {
    let path = clients_file(state_dir);
    let text = match std::fs::read_to_string(&path) {
        Ok(t) => t,
        Err(_) => return vec![],
    };
    serde_json::from_str::<Vec<ClientRecord>>(&text).unwrap_or_default()
}

fn write_client_list(state_dir: &Path, list: &[ClientRecord]) -> Result<(), String> {
    std::fs::create_dir_all(state_dir).map_err(|e| e.to_string())?;
    let temp = clients_file(state_dir).with_extension(format!("json.tmp.{}", std::process::id()));
    let body = serde_json::to_string(list).map_err(|e| e.to_string())?;
    std::fs::write(&temp, body).map_err(|e| e.to_string())?;
    #[cfg(unix)]
    std::fs::set_permissions(&temp, std::fs::Permissions::from_mode(0o600))
        .map_err(|e| e.to_string())?;
    std::fs::rename(&temp, clients_file(state_dir)).map_err(|e| e.to_string())?;
    Ok(())
}

/// Verify a presented bearer against the client sidecar. Only used when the
/// boot/rotating verifier already failed; the file is read on each miss and
/// is tiny (<1 KB for a handful of clients).
pub fn verify_against_clients(state_dir: &Path, presented: &str) -> bool {
    let digest = sha256_digest(presented);
    for record in read_client_list(state_dir) {
        if record.verifier.len() == digest.len()
            && bool::from(record.verifier.as_bytes().ct_eq(digest.as_bytes()))
        {
            return true;
        }
    }
    false
}

/// Ensure the GUI (label `voxix-gui`) has a usable credential. Returns the
/// plaintext — freshly minted on first call — and persists the GUI's copy in
/// `gui-client.json` (0600). Idempotent across launches.
pub fn ensure_gui_client_token(state_dir: &Path) -> Result<String, String> {
    std::fs::create_dir_all(state_dir).map_err(|e| e.to_string())?;

    // 1) A previously stored plaintext that still maps to a client record? Reuse it.
    if let Ok(text) = std::fs::read_to_string(gui_client_file(state_dir)) {
        if let Ok(body) = serde_json::from_str::<BTreeMap<String, serde_json::Value>>(&text) {
            if let Some(token) = body.get("token").and_then(|v| v.as_str()) {
                let digest = sha256_digest(token);
                let records = read_client_list(state_dir);
                if records
                    .iter()
                    .any(|r| r.label == "voxix-gui" && r.verifier == digest)
                {
                    return Ok(token.to_string());
                }
            }
        }
    }

    // 2) Mint a fresh client; reconcile the list atomically.
    let token = generate_token()?;
    let digest = sha256_digest(&token);
    let mut list = read_client_list(state_dir);
    list.retain(|r| r.label != "voxix-gui");
    list.push(ClientRecord {
        label: "voxix-gui".to_string(),
        prefix: token_prefix_of(&token),
        verifier: digest,
        created_at: now_rfc3339(),
    });
    write_client_list(state_dir, &list)?;

    let body = serde_json::json!({
        "label": "voxix-gui",
        "token": token,
        "created_at": now_rfc3339(),
    });
    std::fs::write(gui_client_file(state_dir), body.to_string()).map_err(|e| e.to_string())?;
    #[cfg(unix)]
    std::fs::set_permissions(
        gui_client_file(state_dir),
        std::fs::Permissions::from_mode(0o600),
    )
    .map_err(|e| e.to_string())?;
    Ok(token)
}
