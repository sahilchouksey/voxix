/// Initialize shortcuts using the configured implementation.
/// Returns an error when the active implementation (and any fallback) fails
/// to register the configured bindings, so callers can surface it.
pub fn init_shortcuts(app: &AppHandle) -> Result<(), String> {
    let user_settings = settings::load_or_create_app_settings(app);

    // On Linux, start the rdev modifier listener for modifier-only hotkeys
    #[cfg(target_os = "linux")]
    {
        if let Err(e) = rdev().start(app.clone()) {
            warn!("Failed to start rdev modifier listener: {}", e);
        }
    }

    // Check which implementation to use
    let result = match user_settings.keyboard_implementation {
        KeyboardImplementation::Tauri => tauri_impl::init_shortcuts(app),
        KeyboardImplementation::VoxixKeys => match voxix_keys::init_shortcuts(app) {
            Ok(()) => Ok(()),
            Err(e) => {
                error!("Failed to initialize voxix-keys shortcuts: {}", e);
                // Fall back to Tauri implementation and persist this fallback
                warn!("Falling back to Tauri global shortcut implementation and saving fallback to settings");

                // Update settings to persist the fallback so we don't retry VoxixKeys on next launch
                let mut settings = settings::get_settings(app);
                settings.keyboard_implementation = KeyboardImplementation::Tauri;
                settings::write_settings(app, settings);

                tauri_impl::init_shortcuts(app).map_err(|fallback_err| {
                    format!("voxix-keys failed ({e}); Tauri fallback also failed: {fallback_err}")
                })
            }
        },
    };

    // On Linux, register modifier-only bindings with the rdev backend
    #[cfg(target_os = "linux")]
    {
        for (id, binding) in &user_settings.bindings {
            if is_modifier_only(&binding.current_binding) {
                if let Err(e) = rdev().register(binding) {
                    warn!("Failed to register rdev modifier binding '{}': {}", id, e);
                }
            }
        }
    }

    result
}

/// Register the cancel shortcut (called when recording starts)
pub fn register_cancel_shortcut(app: &AppHandle) {
    // Track recording lifecycle independently of the current implementation so
    // switching implementations mid-recording cannot leave stale fallback state.
    crate::secure_input::register_cancel_fallback(app);

    let settings = get_settings(app);
    match settings.keyboard_implementation {
        KeyboardImplementation::Tauri => tauri_impl::register_cancel_shortcut(app),
        KeyboardImplementation::VoxixKeys => voxix_keys::register_cancel_shortcut(app),
    }
}

/// Unregister the cancel shortcut (called when recording stops)
pub fn unregister_cancel_shortcut(app: &AppHandle) {
    crate::secure_input::unregister_cancel_fallback(app);

    let settings = get_settings(app);
    match settings.keyboard_implementation {
        KeyboardImplementation::Tauri => tauri_impl::unregister_cancel_shortcut(app),
        KeyboardImplementation::VoxixKeys => voxix_keys::unregister_cancel_shortcut(app),
    }
}

/// Register a shortcut using the appropriate implementation
pub fn register_shortcut(app: &AppHandle, binding: ShortcutBinding) -> Result<(), String> {
    // On Linux, modifier-only bindings go through the rdev backend
    #[cfg(target_os = "linux")]
    if is_modifier_only(&binding.current_binding) {
        return rdev().register(&binding);
    }

    let settings = get_settings(app);
    match settings.keyboard_implementation {
        KeyboardImplementation::Tauri => tauri_impl::register_shortcut(app, binding),
        KeyboardImplementation::VoxixKeys => voxix_keys::register_shortcut(app, binding),
    }
}

/// Unregister a shortcut using the appropriate implementation
pub fn unregister_shortcut(app: &AppHandle, binding: ShortcutBinding) -> Result<(), String> {
    let settings = get_settings(app);
    let modifier_only = is_modifier_only(&binding.current_binding);

    // On Linux, modifier-only bindings live in the rdev backend; always clear
    // them there.
    #[cfg(target_os = "linux")]
    if modifier_only {
        rdev().unregister(&binding).map_err(|e| {
            format!(
                "Failed to unregister rdev shortcut '{}': {}",
                binding.current_binding, e
            )
        })?;
    }

    // Never early-return before telling the active backend: a modifier-only
    // hotkey can still sit stale in the voxix-keys HotkeyManager (registered
    // by an older build, before the pure-modifier guard), and a binding change
    // must clear the previous binding in every backend that holds it. The
    // Tauri plugin never holds modifier-only shortcuts (registration diverts
    // them to rdev), so only the VoxixKeys backend needs the cleanup pass.
    if modifier_only {
        return match settings.keyboard_implementation {
            KeyboardImplementation::VoxixKeys => voxix_keys::unregister_shortcut(app, binding),
            KeyboardImplementation::Tauri => Ok(()),
        };
    }

    match settings.keyboard_implementation {
        KeyboardImplementation::Tauri => tauri_impl::unregister_shortcut(app, binding),
        KeyboardImplementation::VoxixKeys => voxix_keys::unregister_shortcut(app, binding),
    }
}

